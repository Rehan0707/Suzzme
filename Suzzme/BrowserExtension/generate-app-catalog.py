#!/usr/bin/env python3
"""Generate native/browser detection from one reviewed, hostname-only catalog."""
import json
from pathlib import Path
root = Path(__file__).resolve().parent
rows = json.loads((root/'app-catalog.json').read_text())
(root/'app-catalog.js').write_text('// Generated by generate-app-catalog.py.\nexport const appCatalog = '+json.dumps(rows,indent=2)+';\n')
swift = '''// Generated by BrowserExtension/generate-app-catalog.py.
import Foundation

enum BrowserAppCatalog {
    struct Entry: Sendable { let service: String; let host: String; let path: String }
    static let entries: [Entry] = [
'''
for row in rows:
 swift += '        .init(service: '+json.dumps(row['service'])+', host: '+json.dumps(row['host'])+', path: '+json.dumps(row['path'])+'),\n'
swift += '''    ]
    static func service(for raw: String) -> String? {
        guard raw.utf8.count <= 4096, !raw.contains("\\\\"),
              !raw.unicodeScalars.contains(where: { CharacterSet.controlCharacters.contains($0) || CharacterSet.whitespaces.contains($0) }),
              let url = URLComponents(string: raw), url.scheme == "https",
              url.user == nil, url.password == nil, url.port == nil || url.port == 443,
              let host = url.host?.lowercased() else { return nil }
        return entries.sorted { $0.path.count > $1.path.count }.first {
            (host == $0.host || host.hasSuffix("." + $0.host)) && url.path.hasPrefix($0.path)
        }?.service
    }
}
'''
(root.parent/'Suzzme/Core/BrowserBridge/BrowserAppCatalog.swift').write_text(swift)
p=root/'manifest.json'; manifest=json.loads(p.read_text())
manifest['optional_host_permissions']=sorted(set(pattern for row in rows for pattern in ['https://'+row['host']+'/*','https://*.'+row['host']+'/*']))
p.write_text(json.dumps(manifest,indent=2)+'\n')
